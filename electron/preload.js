// 렌더러(화면)에서 쓸 수 있는 기능만 골라서 열어준다.
const { contextBridge, ipcRenderer } = require('electron');

const on = (ch) => (fn) => { const h = (_e, ...a) => fn(...a); ipcRenderer.on(ch, h); return () => ipcRenderer.removeListener(ch, h); };

contextBridge.exposeInMainWorld('api', {
  loadState: () => ipcRenderer.invoke('state:load'),
  saveState: (s) => ipcRenderer.invoke('state:save', s),
  setInteractive: (b) => ipcRenderer.send('win:interactive', b),
  focus: () => ipcRenderer.send('win:focus'),
  release: () => ipcRenderer.send('win:release'),
  info: () => ipcRenderer.invoke('app:info'),
  openData: () => ipcRenderer.send('app:openData'),
  quit: () => ipcRenderer.send('app:quit'),
  applySettings: (s) => ipcRenderer.send('settings:apply', s),
  petVisible: (visible) => ipcRenderer.invoke('memo-pet:visible', visible),
  petControls: (action, id) => ipcRenderer.invoke('memo-pet:controls', action, id),
  petScheduleSpeech: (text, id) => ipcRenderer.invoke('memo-pet:schedule-speech', text, id),
  onPetBriefingRequest: on('pet-briefing-request'),
  showPetBriefing: (id, text) => ipcRenderer.send('memo-pet:show-briefing', id, text),
  perchPet: (id) => ipcRenderer.send('pet:perch', id),
  onPetContent: on('pet-content'),
  readWebImage: (url) => ipcRenderer.invoke('image:dropped-url', url),
  onPetPhotos: on('pet-photos'),
  onPetPhotoError: on('pet-photo-error'),
  onPetChanged: on('pet-changed'),
  onPetMenuSelected: on('pet-menu-selected'),
  notify: (o) => ipcRenderer.send('notify', o),
  keyStatus: () => ipcRenderer.invoke('keys:status'),
  setKey: (name, value) => ipcRenderer.invoke('keys:set', name, value),
  testKey: (name) => ipcRenderer.invoke('keys:test', name),
  mergeCandidates: notes => ipcRenderer.invoke('ai:merge-candidates', notes),
  organize: (payload) => ipcRenderer.invoke('ai:organize', payload),
  summarize: (payload) => ipcRenderer.invoke('ai:summarize', payload),
  searchNotes: (payload) => ipcRenderer.invoke('ai:search-notes', payload),
  notion: (action,data) => ipcRenderer.invoke('notion:action', action, data),
  calendar: action => ipcRenderer.invoke('calendar:action', action),
  weather: (city) => ipcRenderer.invoke('weather:get', city),
  convertHeic: (buf) => ipcRenderer.invoke('image:heic', buf),
  onCursor: on('cursor'),
  showPeekDisplay: (id, side) => ipcRenderer.invoke('win:peek-display', id, side),
  onForeground: on('fg'),
  onDisplay: on('display'),
  onCommand: on('cmd'),
  onOpenNote: on('open-note'),
  onBlur: on('win-blur'),
});
